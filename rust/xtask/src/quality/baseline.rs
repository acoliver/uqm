use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;
use std::process::{Command, Stdio};

use super::metrics::{limit, Measurement};

#[derive(Default, Debug, PartialEq, Eq)]
pub struct Baseline {
    pub entries: BTreeMap<String, u64>,
    pub moved: BTreeMap<String, String>,
    pub budget: BTreeMap<String, super::budgets::Budget>,
    pub layers: bool,
    pub lint: BTreeMap<String, BTreeMap<String, u64>>,
}

impl Baseline {
    pub fn read(path: &Path) -> Result<Self, String> {
        let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        Self::parse(&text)
    }
    fn parse(text: &str) -> Result<Self, String> {
        let document = text
            .parse::<toml_edit::DocumentMut>()
            .map_err(|e| e.to_string())?;
        let mut result = Self {
            layers: document
                .get("layers")
                .and_then(|v| v.as_bool())
                .unwrap_or(false),
            ..Self::default()
        };
        if let Some(table) = document.get("lint").and_then(toml_edit::Item::as_table) {
            // Baselines at older git refs were measured on Linux only.
            if table.iter().all(|(_, value)| value.is_integer()) {
                result.lint.insert("linux".into(), lint_values(table)?);
            } else {
                for (host, value) in table {
                    let values = value
                        .as_table()
                        .ok_or_else(|| format!("invalid lint host section: {host}"))?;
                    result.lint.insert(host.into(), lint_values(values)?);
                }
            }
        }
        if let Some(item) = document.get("budget") {
            result.budget =
                super::budgets::parse(item.as_table().ok_or("invalid budget section")?)?;
        }
        if let Some(table) = document.get("entry").and_then(toml_edit::Item::as_table) {
            for (key, value) in table {
                let value = value
                    .as_integer()
                    .ok_or_else(|| format!("baseline {key} is not an integer"))?;
                result
                    .entries
                    .insert(key.into(), u64::try_from(value).map_err(|e| e.to_string())?);
            }
        }
        if let Some(table) = document.get("moved").and_then(toml_edit::Item::as_table) {
            for (key, value) in table {
                result.moved.insert(
                    key.into(),
                    value.as_str().ok_or("move target is not a string")?.into(),
                );
            }
        }
        Ok(result)
    }
    pub fn write(&self, path: &Path) -> Result<(), String> {
        let mut document = toml_edit::DocumentMut::new();
        document.insert("layers", toml_edit::value(self.layers));
        if !self.lint.is_empty() {
            let mut hosts = toml_edit::Table::new();
            hosts.set_implicit(true);
            for (host, values) in &self.lint {
                let mut table = toml_edit::Table::new();
                for (key, value) in values {
                    table.insert(
                        key,
                        toml_edit::value(i64::try_from(*value).map_err(|e| e.to_string())?),
                    );
                }
                hosts.insert(host, toml_edit::Item::Table(table));
            }
            document.insert("lint", toml_edit::Item::Table(hosts));
        }
        if !self.budget.is_empty() {
            document.insert(
                "budget",
                toml_edit::Item::Table(super::budgets::write(&self.budget)?),
            );
        }
        let mut entries = toml_edit::Table::new();
        for (key, value) in &self.entries {
            entries.insert(
                key,
                toml_edit::value(i64::try_from(*value).map_err(|e| e.to_string())?),
            );
        }
        document.insert("entry", toml_edit::Item::Table(entries));
        let mut moves = toml_edit::Table::new();
        for (old, new) in &self.moved {
            moves.insert(old, toml_edit::value(new));
        }
        document.insert("moved", toml_edit::Item::Table(moves));
        fs::write(
            path,
            format!("# Generated by cargo xtask quality --tighten. Values only fall.\n{document}"),
        )
        .map_err(|e| e.to_string())
    }
    pub fn rekey(&mut self, renames: &BTreeMap<String, String>) -> Result<(), String> {
        for (old, new) in renames.iter().rev() {
            self.entries = move_entries(&self.entries, old, new, true)?;
        }
        Ok(())
    }

    pub fn tighten(
        &mut self,
        measurement: &Measurement,
        base: Option<&Baseline>,
    ) -> Result<(), String> {
        let measured = measurement.baseline();
        super::budgets::check(measurement, &self.budget)?;
        if !self.entries.is_empty() {
            check_limits(
                &super::budgets::without_budgeted(&measured, &self.budget),
                &super::budgets::without_budgeted(&self.entries, &self.budget),
                &self.moved,
                false,
            )?;
        }
        self.entries = measured;
        if let Some(base) = base {
            self.moved.retain(|_, target| {
                !base
                    .entries
                    .keys()
                    .any(|k| identity(k).is_some_and(|id| prefix_matches(id, target)))
            });
        }
        Ok(())
    }
    pub fn add_move(
        &mut self,
        old: &str,
        new: &str,
        current: &Measurement,
        base: &Measurement,
    ) -> Result<(), String> {
        let mut moves = self.moved.clone();
        super::transfers::register(&mut moves, old, new)?;
        super::transfers::validate(current, base, &moves)?;
        let before = super::transfers::limits(&base.baseline(), current, base, &self.moved)?;
        let after = super::transfers::limits(&base.baseline(), current, base, &moves)?;
        let entries = super::transfers::adjust(&self.entries, &before, &after)?;
        let lint = self
            .lint
            .iter()
            .map(|(host, values)| Ok((host.clone(), move_entries(values, old, new, true)?)))
            .collect::<Result<_, String>>()?;
        self.entries = entries;
        self.lint = lint;
        self.moved = moves;
        Ok(())
    }
}

fn lint_values(table: &toml_edit::Table) -> Result<BTreeMap<String, u64>, String> {
    table
        .iter()
        .map(|(key, value)| {
            let count = value
                .as_integer()
                .and_then(|v| u64::try_from(v).ok())
                .ok_or_else(|| format!("invalid lint value: {key}"))?;
            Ok((key.into(), count))
        })
        .collect()
}

fn move_entries(
    entries: &BTreeMap<String, u64>,
    old: &str,
    new: &str,
    prefix: bool,
) -> Result<BTreeMap<String, u64>, String> {
    let mut result = entries.clone();
    for (key, value) in entries {
        let id = key.rsplit_once('|').map_or(key.as_str(), |(_, id)| id);
        if (prefix && prefix_matches(id, old)) || (!prefix && id == old) {
            let target_id = format!("{new}{}", &id[old.len()..]);
            let target_key = key
                .rsplit_once('|')
                .map_or(target_id.clone(), |(head, _)| format!("{head}|{target_id}"));
            if entries.contains_key(&target_key) {
                return Err(format!("move would merge debt into {target_key}"));
            }
            result.remove(key);
            result.insert(target_key, *value);
        }
    }
    Ok(result)
}

fn identity(key: &str) -> Option<&str> {
    key.splitn(3, '|').nth(2)
}
fn prefix_matches(value: &str, prefix: &str) -> bool {
    value == prefix
        || value
            .strip_prefix(prefix)
            .is_some_and(|s| s.starts_with("::"))
}
fn default_limit(key: &str) -> u64 {
    let mut parts = key.split('|');
    limit(
        parts.next().unwrap_or_default(),
        parts.next().unwrap_or_default(),
    )
}

fn transferred(
    key: &str,
    base: &BTreeMap<String, u64>,
    current: &BTreeMap<String, u64>,
    moves: &BTreeMap<String, String>,
) -> Result<Option<u64>, String> {
    let Some(id) = identity(key) else {
        return Err(format!("invalid baseline key {key}"));
    };
    let mut credits = Vec::new();
    for (old, new) in moves {
        if prefix_matches(id, new) {
            let source = format!(
                "{}|{old}{}",
                key.rsplit_once('|').unwrap().0,
                &id[new.len()..]
            );
            if current.contains_key(&source) {
                return Err(format!("move source {source} still has debt"));
            }
            if let Some(value) = base.get(&source) {
                credits.push(*value);
            }
        }
    }
    if credits.len() > 1 {
        return Err(format!("multiple move credits for {key}"));
    }
    Ok(credits.first().copied())
}

pub fn check_limits(
    current: &BTreeMap<String, u64>,
    base: &BTreeMap<String, u64>,
    moves: &BTreeMap<String, String>,
    against_base: bool,
) -> Result<(), String> {
    let mut errors = Vec::new();
    let unsafe_metrics: BTreeSet<_> = current
        .keys()
        .chain(base.keys())
        .filter(|k| k.starts_with("unsafe|"))
        .filter_map(|k| k.split('|').nth(1))
        .collect();
    for metric in unsafe_metrics {
        let prefix = format!("unsafe|{metric}|");
        let before: u64 = base
            .iter()
            .filter(|(k, _)| k.starts_with(&prefix))
            .map(|(_, v)| v)
            .sum();
        let after: u64 = current
            .iter()
            .filter(|(k, _)| k.starts_with(&prefix))
            .map(|(_, v)| v)
            .sum();
        if after > before {
            errors.push(format!("workspace {metric}: {before} -> {after}"));
        }
    }
    for (key, value) in current {
        if key.starts_with("unsafe|") {
            continue;
        }
        let credit = transferred(key, base, current, moves)?;
        let allowed = base
            .get(key)
            .copied()
            .or(credit)
            .unwrap_or_else(|| default_limit(key));
        if *value > allowed {
            errors.push(format!("{key}: {allowed} -> {value}"));
        }
    }
    // Transfers cannot create headroom by changing crate names or combining sources.
    if against_base && !moves.is_empty() {
        let mut old_totals = BTreeMap::<String, u64>::new();
        let mut new_totals = BTreeMap::<String, u64>::new();
        for (entries, totals) in [(base, &mut old_totals), (current, &mut new_totals)] {
            for (key, value) in entries {
                let mut parts = key.split('|');
                let counter = parts.next().unwrap_or_default();
                let metric = parts.next().unwrap_or_default();
                if ["loc", "complexity"].contains(&counter) {
                    continue;
                }
                *totals.entry(format!("{counter}|{metric}")).or_default() += value;
            }
        }
        for (key, after) in new_totals {
            let before = old_totals.get(&key).copied().unwrap_or(0);
            if after > before {
                errors.push(format!("transfer total {key}: {before} -> {after}"));
            }
        }
    }
    if errors.is_empty() {
        Ok(())
    } else {
        Err(format!("quality growth:\n{}", errors.join("\n")))
    }
}

pub fn validate_transfers(
    current: &Measurement,
    base: &Measurement,
    moves: &BTreeMap<String, String>,
) -> Result<(), String> {
    super::transfers::validate(current, base, moves)
}

pub fn baseline_at_ref(root: &Path, reference: &str) -> Result<Option<Baseline>, String> {
    let path = "rust/xtask/quality-baseline.toml";
    let listed = Command::new("git")
        .current_dir(root)
        .args(["ls-tree", "--name-only", reference, "--", path])
        .output()
        .map_err(|e| e.to_string())?;
    if !listed.status.success() {
        return Err(format!(
            "git ls-tree {reference}: {}",
            String::from_utf8_lossy(&listed.stderr)
        ));
    }
    if listed.stdout.is_empty() {
        return Ok(None);
    }
    let output = Command::new("git")
        .current_dir(root)
        .args(["show", &format!("{reference}:{path}")])
        .output()
        .map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "git show baseline: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Baseline::parse(&String::from_utf8(output.stdout).map_err(|e| e.to_string())?).map(Some)
}

pub fn archived_measurement(
    root: &Path,
    reference: &str,
) -> Result<(Measurement, Option<Baseline>), String> {
    let directory = root.join("rust/target/xtask-base");
    fs::create_dir_all(&directory).map_err(|e| e.to_string())?;
    let archive = tempfile::tempdir_in(directory).map_err(|e| e.to_string())?;
    let mut git = Command::new("git")
        .current_dir(root)
        .args(["archive", reference])
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| e.to_string())?;
    let status = Command::new("tar")
        .arg("-x")
        .arg("-C")
        .arg(archive.path())
        .stdin(git.stdout.take().ok_or("git archive stdout missing")?)
        .status()
        .map_err(|e| e.to_string())?;
    let git_status = git.wait().map_err(|e| e.to_string())?;
    if !status.success() || !git_status.success() {
        return Err(format!(
            "git archive {reference} failed: {git_status}, tar: {status}"
        ));
    }
    let baseline_path = archive.path().join("rust/xtask/quality-baseline.toml");
    let mut baseline = if baseline_path.exists() {
        Some(Baseline::read(&baseline_path)?)
    } else {
        None
    };
    let measurement = super::walk::measure(archive.path(), None, false)?;
    if let Some(baseline) = &mut baseline {
        baseline.rekey(&measurement.identity_renames)?;
    }
    Ok((measurement, baseline))
}

#[cfg(test)]
mod tests {
    use super::*;
    fn entries(rows: &[(&str, u64)]) -> BTreeMap<String, u64> {
        rows.iter().map(|(k, v)| (k.to_string(), *v)).collect()
    }
    fn move_baseline(baseline: &mut Baseline, old: &str, new: &str) -> Result<(), String> {
        use super::super::metrics::Finding;
        let mut base = Measurement::default();
        for key in baseline
            .entries
            .keys()
            .chain(baseline.lint.values().flat_map(|v| v.keys()))
        {
            let id = key.rsplit_once('|').unwrap().1;
            let parts: Vec<_> = key.split('|').collect();
            base.findings.push(Finding {
                counter: if parts.len() == 3 { parts[0] } else { "loc" }.into(),
                metric: if parts.len() == 3 { parts[1] } else { "loc" }.into(),
                identity: id.into(),
                file: "src/lib.rs".into(),
                package: id.split("::").next().unwrap().into(),
                subsystem: id.split("::").nth(1).unwrap().into(),
                value: baseline.entries.get(key).copied().unwrap_or(0),
            });
        }
        let current = Measurement {
            findings: base
                .findings
                .iter()
                .map(|f| {
                    let mut f = f.clone();
                    f.identity = f.identity.replacen(old, new, 1);
                    f.package = new.split("::").next().unwrap().into();
                    f
                })
                .collect(),
            ..Default::default()
        };
        baseline.add_move(old, new, &current, &base)
    }
    #[test]
    fn baseline_roundtrip_tightening_and_growth() {
        let b = Baseline {
            entries: entries(&[("ffi|static_mut|uqm::battle", 3)]),
            ..Baseline::default()
        };
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("baseline.toml");
        b.write(&path).unwrap();
        assert_eq!(Baseline::read(&path).unwrap(), b);
        assert!(check_limits(
            &entries(&[("ffi|static_mut|uqm::battle", 4)]),
            &b.entries,
            &BTreeMap::new(),
            false
        )
        .is_err());
        assert!(check_limits(&BTreeMap::new(), &b.entries, &BTreeMap::new(), false).is_ok());
    }
    #[test]
    fn prefix_transfer_requires_source_disappearance_and_does_not_duplicate_credit() {
        let before = entries(&[("complexity|loc|uqm::graphics::load", 100)]);
        let mut b = Baseline {
            entries: before.clone(),
            ..Baseline::default()
        };
        move_baseline(&mut b, "uqm::graphics", "uqm-engine::graphics").unwrap();
        assert!(check_limits(&b.entries, &before, &b.moved, true).is_ok());
        let mut both = b.entries.clone();
        both.extend(before.clone());
        assert!(check_limits(&both, &before, &b.moved, true).is_err());
        assert!(b
            .add_move(
                "uqm-engine::graphics",
                "uqm-engine::graphics",
                &Measurement::default(),
                &Measurement::default()
            )
            .is_err());
    }
    #[test]
    fn a_function_left_below_the_default_limit_is_not_a_valid_transfer() {
        use super::super::metrics::Finding;
        let finding = |name: &str| Finding {
            counter: "complexity".into(),
            metric: "loc".into(),
            identity: name.into(),
            file: "src/lib.rs".into(),
            package: "uqm".into(),
            subsystem: "lib".into(),
            value: 50,
        };
        let base = Measurement {
            findings: vec![finding("uqm::old")],
            ..Measurement::default()
        };
        let mut current = Measurement {
            findings: vec![finding("uqm::new"), finding("uqm::old")],
            ..Measurement::default()
        };
        let moves = [("uqm::old".into(), "uqm::new".into())].into();
        assert!(validate_transfers(&current, &base, &moves).is_err());
        current.findings.pop();
        assert!(validate_transfers(&current, &base, &moves).is_ok());
    }
    #[test]
    fn legacy_baselines_are_linux_only_and_host_values_are_validated() {
        let legacy = Baseline::parse(
            r#"[lint]
"unwrap|uqm::a" = 2
"#,
        )
        .unwrap();
        assert_eq!(legacy.lint.len(), 1);
        assert_eq!(legacy.lint["linux"], entries(&[("unwrap|uqm::a", 2)]));
        assert!(Baseline::parse(
            r#"[lint.macos]
"unwrap|uqm::a" = -1
"#
        )
        .is_err());
        assert!(Baseline::parse(
            r#"[lint]
macos = "invalid"
"#
        )
        .is_err());
    }

    #[test]
    fn prefix_move_rewrites_lint_section() {
        let mut baseline = Baseline {
            lint: [
                (
                    "linux".into(),
                    entries(&[("unwrap_used|uqm::graphics::draw::@file", 2)]),
                ),
                (
                    "macos".into(),
                    entries(&[("unwrap_used|uqm::graphics::draw::@file", 3)]),
                ),
            ]
            .into(),
            ..Baseline::default()
        };
        move_baseline(&mut baseline, "uqm::graphics", "uqm-engine::graphics").unwrap();
        for (host, count) in [("linux", 2), ("macos", 3)] {
            assert_eq!(
                baseline.lint[host],
                entries(&[("unwrap_used|uqm-engine::graphics::draw::@file", count)])
            );
        }
        let root = super::super::tool::fixture_directory();
        let path = root.path().join("baseline.toml");
        baseline.write(&path).unwrap();
        assert_eq!(Baseline::read(&path).unwrap(), baseline);
    }
    #[test]
    fn unsafe_transfers_use_each_workspace_metric_total() {
        let before = entries(&[("unsafe|unsafe_blocks|uqm::battle", 3)]);
        let after = entries(&[("unsafe|unsafe_blocks|uqm::engine", 3)]);
        assert!(check_limits(&after, &before, &BTreeMap::new(), true).is_ok());
        let growth = entries(&[("unsafe|unsafe_blocks|uqm::engine", 4)]);
        assert!(check_limits(&growth, &before, &BTreeMap::new(), true).is_err());
    }
}
