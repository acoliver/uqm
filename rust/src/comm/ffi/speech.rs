//! Pending speech is resolved before the communication frame handles responses.

use crate::comm::talk_segue;
use crate::comm::Comm;
use crate::engine::{
    battle::Cx,
    observe::{CheckpointView, InputView, Io},
};

pub(super) fn run_pending(
    comm: &mut Comm,
    _input: &crate::engine::input::InputSession,
    cx: &mut Cx<'_>,
    io: &mut Io<'_>,
) -> bool {
    #[cfg(not(test))]
    use talk_segue::WAIT_TRACK_ALL;
    let is_finished = comm.is_talking_finished();
    eprintln!(
        "[DBG] rust_DoCommunication: is_talking_finished={}",
        is_finished
    );
    if !is_finished {
        // First-call initialization (only once per encounter)
        {
            let state = &mut *comm;
            if !state.first_talk_call {
                state.first_talk_call = true;
                // Drop lock before calling C bridges

                talk_segue::alien_talk_first_call_init(comm, cx);
            }
        }

        // Responses may already have been generated by the callback, but
        // they are not selectable until this speech segment finishes.
        io.observer
            .checkpoint(&CheckpointView::ResponsesReady(false));

        let response_count = comm.responses().count();
        let semantic_skip = comm
            .admit_observer(io, &InputView::PendingSpeech, cx)
            .stop
            || comm
                .admit_observer(
                    io,
                    &InputView::PendingResponse {
                        count: response_count,
                    },
                    cx,
                )
                .stop
            || comm
                .admit_observer(io, &InputView::ClosingSpeech, cx)
                .stop;
        if semantic_skip {
            let _ = crate::sound::trackplayer::jump_track(0);
        }

        // Run talk segue via Rust DoInput — NO Rust lock held
        #[cfg(not(test))]
        let ended = if semantic_skip {
            true
        } else {
            talk_segue::dinput::run_talk_segue_dinput(comm, _input, cx, io, WAIT_TRACK_ALL)
        };
        #[cfg(test)]
        let ended = true;

        // Update state with result
        comm.set_talking_finished(ended);

        if ended {
            talk_segue::fade_music_to_foreground_bridge();
        }

        return true;
    }
    false
}
