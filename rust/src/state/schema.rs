#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packed_fields_cover_the_save_bytes_without_gaps_or_overlap() {
        let mut next = 0;
        let mut names = std::collections::HashSet::new();
        for &(name, start, end) in GAME_STATE_FIELDS {
            assert!(names.insert(name), "duplicate field {name}");
            assert_eq!(start, next, "{name}");
            assert!((start..start + 8).contains(&end), "{name}");
            assert_eq!(lookup_game_state_bits(name), Some((start, end)));
            next = end + 1;
        }
        assert_eq!(next, 1238);
        assert_eq!(NUM_GAME_STATE_BITS, next);
        assert_eq!(NUM_GAME_STATE_BYTES, next.div_ceil(8));
        assert_eq!(lookup_game_state_bits("unknown"), None);
    }

    #[test]
    fn save_field_positions_and_widths_remain_stable() {
        for (name, range) in [
            ("SHOFIXTI_VISITS", (0, 2)),
            ("SHOFIXTI_STACK2", (5, 7)),
            ("SHOFIXTI_STACK3", (8, 9)),
            ("SHOFIXTI_RECRUITED", (12, 12)),
            ("SAMATRA_GRPOFFS3", (1230, 1237)),
        ] {
            assert_eq!(lookup_game_state_bits(name), Some(range));
        }
    }
}
