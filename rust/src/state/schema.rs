//! Packed story-state fields. Positions are part of the save format.

pub const NUM_GAME_STATE_BITS: usize = 1238;
const _: () = assert!(NUM_GAME_STATE_BITS.div_ceil(8) == super::NUM_GAME_STATE_BYTES);

macro_rules! game_state_fields {
    ($($name:ident ($end_name:ident): $start:literal..=$end:literal,)*) => {
        #[cfg(not(test))]
        const _: () = {
            $(
                assert!(crate::navigation::abi::$name as usize == $start);
                assert!(crate::navigation::abi::$end_name as usize == $end);
                assert!(crate::ships::native::abi::$name as usize == $start);
                assert!(crate::ships::native::abi::$end_name as usize == $end);
            )*
        };

        pub const GAME_STATE_FIELDS: &[(&str, usize, usize)] = &[
            $((stringify!($name), $start, $end),)*
        ];

        pub fn lookup_game_state_bits(name: &str) -> Option<(usize, usize)> {
            match name {
                $(stringify!($name) => Some(($start, $end)),)*
                _ => None,
            }
        }
    };
}

