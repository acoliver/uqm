//! The `plandata.c` tables: the star catalog, the element category table
//! and the planet-frame table.
//!
//! The values and layout are the C ones, byte for byte: C reads them through
//! `star_array`, `Elements` and `PlanData` using the generated `STAR_DESC` and
//! `PlanetFrame` layouts, so the entries here use those same layouts.

use std::ffi::{c_char, CStr};

use crate::c_bindings::global_state::{PlanetFrame, ELEMENT_ENTRY};
use crate::comm::dispatch::CPoint;
use crate::savegame::runtime::star::{CStarDesc, CATALOG_LEN};

/// Entries of `starmap_array`, including the terminating sentinel.
pub const STAR_CATALOG_LEN: usize = CATALOG_LEN;
/// `NUMBER_OF_ELEMENTS`.
pub const ELEMENT_COUNT: usize = 133;
/// `NUMBER_OF_PLANET_TYPES`.
pub const PLANET_TYPE_COUNT: usize = 59;

/// An immutable table whose pointers all refer to `'static` NUL-terminated
/// strings, so sharing it between threads is sound.
#[repr(transparent)]
pub struct SharedTable<T>(pub T);

// SAFETY: the table is never written and holds only `'static` string pointers.
unsafe impl<T> Sync for SharedTable<T> {}

const fn star(x: i16, y: i16, star_type: u8, index: u8, prefix: u8, postfix: u8) -> CStarDesc {
    CStarDesc {
        star_pt: CPoint { x, y },
        star_type,
        index,
        prefix,
        postfix,
    }
}

const fn mineral(element: u8, density: u8) -> ELEMENT_ENTRY {
    ELEMENT_ENTRY {
        ElementType: element,
        Density: density,
    }
}

const fn resource(name: &'static CStr) -> *const c_char {
    name.as_ptr()
}

const fn frame(
    kind: u8,
    tectonics: u8,
    atmosphere_and_density: u8,
    minerals: [(u8, u8); 8],
    (color_map, translate_table): (&'static CStr, &'static CStr),
    (num_faults, fault_depth): (u16, i16),
    (num_blemishes, base_elevation): (u16, i16),
) -> PlanetFrame {
    PlanetFrame {
        Type: kind,
        BaseTectonics: tectonics,
        AtmoAndDensity: atmosphere_and_density,
        UsefulElements: [
            mineral(minerals[0].0, minerals[0].1),
            mineral(minerals[1].0, minerals[1].1),
            mineral(minerals[2].0, minerals[2].1),
            mineral(minerals[3].0, minerals[3].1),
            mineral(minerals[4].0, minerals[4].1),
            mineral(minerals[5].0, minerals[5].1),
            mineral(minerals[6].0, minerals[6].1),
            mineral(minerals[7].0, minerals[7].1),
        ],
        CMapInstance: resource(color_map),
        XlatTabInstance: resource(translate_table),
        num_faults,
        fault_depth,
        num_blemishes,
        base_elevation,
    }
}

